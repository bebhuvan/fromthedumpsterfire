#!/usr/bin/env python3
# Writes packages/shared/src/charts/geo/world.ts: the world's countries for the choropleth, from
# Natural Earth's Admin 0 countries in India's point of view (public domain; India's claimed
# boundaries, as India depicts them), projected with Equal Earth (equal-area, so shaded areas compare
# honestly) and simplified to about half a pixel at the 720 px wide figure. Antarctica is left out.
#
#   curl -L -o /tmp/ne_ind.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries_ind.geojson
#   python3 scripts/chart-world.py /tmp/ne_ind.geojson
import json, math, os, sys

src = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', 'packages', 'shared', 'src', 'charts', 'geo', 'world.ts')

A1, A2, A3, A4 = 1.340264, -0.081106, 0.000893, 0.003796
M = math.sqrt(3) / 2

def equal_earth(lon, lat):
    l, p = math.radians(lon), math.radians(lat)
    t = math.asin(M * math.sin(p))
    t2 = t * t; t6 = t2 * t2 * t2
    x = 2 * math.sqrt(3) * l * math.cos(t) / (3 * (9 * A4 * t6 * t2 + 7 * A3 * t6 + 3 * A2 * t2 + A1))
    y = t * (A4 * t6 * t2 + A3 * t6 + A2 * t2 + A1)
    return x, y

XMAX = 2.7064
W = 1000.0
K = W / (2 * XMAX)

def proj(pt):
    x, y = equal_earth(pt[0], pt[1])
    return ((x + XMAX) * K, (1.3173 - y) * K)

def dp(pts, tol):
    """Douglas-Peucker on a closed ring's points (first == last)."""
    if len(pts) < 4: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay; n = math.hypot(dx, dy) or 1e-12
        far, idx = -1, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / n if n > 1e-12 else math.hypot(px - ax, py - ay)
            if d > far: far, idx = d, i
        if far > tol:
            keep[idx] = True; stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]

def area(r):
    return 0.5 * abs(sum(r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1] for i in range(len(r))))

TOL = 0.35   # in the 1000-wide space: 0.25 px at 720 px
MIN_AREA = 0.6
CODE = {'JEY': 'CHI', 'GGY': 'CHI'}

g = json.load(open(src))
rows = []
for f in g['features']:
    p = f['properties']
    adm = p['ADM0_A3']
    if adm == 'ATA': continue
    iso = p.get('ISO_A3') if p.get('ISO_A3') not in (None, '-99') else adm
    iso = CODE.get(adm, iso)
    geom = f['geometry']
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    parts = []
    # Where a label points: the area-weighted centre of the largest piece.
    big = max((poly[0] for poly in polys), key=lambda r: area([proj(q) for q in r]))
    bp = [proj(q) for q in big]
    a2 = sum(bp[i - 1][0] * bp[i][1] - bp[i][0] * bp[i - 1][1] for i in range(len(bp)))
    if abs(a2) > 1e-9:
        lx = sum((bp[i - 1][0] + bp[i][0]) * (bp[i - 1][0] * bp[i][1] - bp[i][0] * bp[i - 1][1]) for i in range(len(bp))) / (3 * a2)
        ly = sum((bp[i - 1][1] + bp[i][1]) * (bp[i - 1][0] * bp[i][1] - bp[i][0] * bp[i - 1][1]) for i in range(len(bp))) / (3 * a2)
    else:
        lx = sum(x for x, _ in bp) / len(bp); ly = sum(y for _, y in bp) / len(bp)
    for poly in polys:
        for ri, ring in enumerate(poly):
            pts = dp([proj(q) for q in ring], TOL)
            if len(pts) < 4 or area(pts) < MIN_AREA: continue
            # Relative moves in tenths of a unit keep the file small.
            s = []; px = py = 0
            for i, (x, y) in enumerate(pts[:-1]):
                xi, yi = round(x * 10), round(y * 10)
                if i == 0: s.append(f'M{xi / 10:g} {yi / 10:g}')
                else: s.append(f'l{(xi - px) / 10:g} {(yi - py) / 10:g}')
                px, py = xi, yi
            s.append('z')
            parts.append(''.join(s).replace('l-', 'l-').replace(' -', '-'))
    if parts:
        rows.append((iso, p['NAME'], p.get('NAME_LONG') or p['NAME'], ''.join(parts), (lx, ly)))
    else:
        # Too small to draw at this scale (island states, city states): a point at the centre of its
        # largest piece, which the map draws as a small dot so its value still shows.
        rows.append((iso, p['NAME'], p.get('NAME_LONG') or p['NAME'], f'P{lx:.1f} {ly:.1f}', (lx, ly)))

# The map's own height once Antarctica is gone.
import re
ys = []
for _, _, _, d, _ in rows:
    x = y = 0.0
    for cmd, a, b in re.findall(r'([MlP])(-?[\d.]+)\s?(-?[\d.]+)', d):
        a, b = float(a), float(b)
        if cmd in 'MP': x, y = a, b
        else: x += a; y += b
        ys.append(y)
top, bottom = min(ys), max(ys)
rows.sort()
lines = [
    '// Generated by scripts/chart-world.py from Natural Earth 5.1.1, Admin 0 countries, point of view: India',
    '// (public domain; naturalearthdata.com). Equal Earth projection, 1000 units wide. Do not edit.',
    '',
    '/** Each country: its ISO 3166 alpha-3 code (as the World Bank and Our World in Data use), names, outline (or "P x y": a point, for a country too small to draw), and where a label points. */',
    'export const WORLD: ReadonlyArray<readonly [code: string, name: string, longName: string, d: string, labelX: number, labelY: number]> = [',
]
for iso, name, long, d, (lx, ly) in rows:
    lines.append(f'  [{json.dumps(iso)}, {json.dumps(name, ensure_ascii=False)}, {json.dumps(long, ensure_ascii=False)}, {json.dumps(d)}, {lx:.1f}, {ly:.1f}],')
lines.append('];')
lines.append(f'/** The outlines span y from {top:.1f} to {bottom:.1f} (Antarctica is left out). */')
lines.append(f'export const WORLD_BOX = {{ width: 1000, top: {top:.1f}, bottom: {bottom:.1f} }} as const;')
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out, len(rows), 'countries', os.path.getsize(out), 'bytes')
