#!/usr/bin/env python3
# Writes packages/shared/src/charts/metrics.ts: advance widths of the chart faces, so the chart
# renderer can measure labels (collisions, margins) the same way on the website and in the PNG.
# Needs fonttools: pip install fonttools. Run after the font cuts change:
#   python3 scripts/chart-metrics.py
import os
from fontTools.ttLib import TTFont

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'apps', 'mobile', 'assets', 'fonts')
out = os.path.join(here, '..', 'packages', 'shared', 'src', 'charts', 'metrics.ts')
faces = {'sans': 'Schibsted-Regular', 'sansMedium': 'Schibsted-Medium', 'serif': 'NewsreaderText-Regular', 'serifItalic': 'NewsreaderText-Italic', 'display': 'NewsreaderDisplay-Medium'}

lines = [
    '// Generated by scripts/chart-metrics.py from the app\'s font cuts. Do not edit.',
    '// Advance widths in thousandths of an em, by code point, for the faces charts set text in.',
    '',
    'export type ChartFace = ' + ' | '.join(f"'{k}'" for k in faces) + ';',
    '',
    'export const ADVANCES: Record<ChartFace, { fallback: number; widths: string }> = {',
]
for key, name in faces.items():
    f = TTFont(os.path.join(src, name + '.ttf'))
    upem = f['head'].unitsPerEm
    cmap = f.getBestCmap()
    hmtx = f['hmtx']
    pairs = []
    for cp in sorted(cmap):
        if cp < 0x20 or cp > 0x2BFF:
            continue
        w = round(hmtx[cmap[cp]][0] * 1000 / upem)
        pairs.append(f'{cp:x}:{w}')
    fallback = round(hmtx[cmap[ord('n')]][0] * 1000 / upem)
    lines.append(f"  {key}: {{ fallback: {fallback}, widths: '{','.join(pairs)}' }},")
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out)
