#!/usr/bin/env python3
# Writes packages/shared/src/charts/marks.ts: the brand's marks (apps/web/public/marks: the flame with
# its globe, the hand-drawn strike and the proofreader's caret) as plain absolute paths in a unit box,
# so a chart scene (the share card) can draw them at any size without masks. The flame's globe is
# returned as lines to paint in the ground colour over the flame, which on a solid ground is the same
# as the mask the website uses. Run after a mark changes:  python3 scripts/chart-marks.py
import os, re

here = os.path.dirname(os.path.abspath(__file__))
marks = os.path.join(here, '..', 'apps', 'web', 'public', 'marks')
out = os.path.join(here, '..', 'packages', 'shared', 'src', 'charts', 'marks.ts')

def tokens(d):
    return re.findall(r'[MmCcLlZzHhVvSsQq]|-?\d*\.?\d+(?:e-?\d+)?', d)

def absolute(d):
    """Parse a path of M/L/C/Z (absolute or relative) into absolute segments [(cmd, [pts])]."""
    t = tokens(d); i = 0; cmd = None; cx = cy = sx = sy = 0.0; segs = []
    def num():
        nonlocal i
        v = float(t[i]); i += 1; return v
    while i < len(t):
        if re.match(r'[A-Za-z]', t[i]):
            cmd = t[i]; i += 1
            if cmd in 'Zz':
                segs.append(('Z', [])); cx, cy = sx, sy; continue
        rel = cmd.islower(); C = cmd.upper()
        if C == 'M':
            x, y = num(), num()
            if rel: x += cx; y += cy
            segs.append(('M', [(x, y)])); cx, cy = sx, sy = x, y
            cmd = 'l' if rel else 'L'
        elif C == 'L':
            x, y = num(), num()
            if rel: x += cx; y += cy
            segs.append(('L', [(x, y)])); cx, cy = x, y
        elif C == 'C':
            pts = []
            for _ in range(3):
                x, y = num(), num()
                if rel: x += cx; y += cy
                pts.append((x, y))
            segs.append(('C', pts)); cx, cy = pts[-1]
        else:
            raise ValueError('unsupported command ' + cmd)
    return segs

def matrix(*ops):
    """Compose transforms given outermost first: ('t', x, y) or ('s', sx, sy)."""
    def apply(p):
        x, y = p
        for op in reversed(ops):
            if op[0] == 't': x, y = x + op[1], y + op[2]
            else: x, y = x * op[1], y * op[2]
        return (x, y)
    return apply

def fmt(segs, f, box):
    x0, y0, w, h = box
    parts = []
    for c, pts in segs:
        if c == 'Z': parts.append('Z'); continue
        q = [f(p) for p in pts]
        parts.append(c + ' '.join(f'{(x - x0) / w:.4f},{(y - y0) / h:.4f}' for x, y in q))
    return ''.join(parts)

read = lambda n: open(os.path.join(marks, n)).read()
path_of = lambda s: re.search(r' d="([^"]+)"', s).group(1)

# Flame: viewBox 27 6 46 88; outer transform, inner transform, and the path's own.
flame_svg = read('flame.svg')
box = (27, 6, 46, 88)
fl = matrix(('t', 50, 53), ('s', 1.6, 1.6), ('t', -50, -42), ('t', 50, 56), ('s', 1.05, 1.05), ('t', -50, -56), ('t', 0, 4), ('s', 1, 1.05))
flame = fmt(absolute(path_of(flame_svg)), fl, box)
# The globe: centre (50, 52) inside translate(50 53) scale(1.6) translate(-50 -42).
g = matrix(('t', 50, 53), ('s', 1.6, 1.6), ('t', -50, -42))
gx, gy = g((50, 52))
globe = {'cx': (gx - box[0]) / box[2], 'cy': (gy - box[1]) / box[3], 'r': 11 * 1.6, 'rx': 4.8 * 1.6, 'ring': 1.6 * 1.6, 'line': 1.3 * 1.6}
strike = fmt(absolute(path_of(read('strike.svg'))), lambda p: p, (0, 0, 400, 40))
caret = fmt(absolute(path_of(read('caret.svg'))), lambda p: p, (0, 0, 40, 30))

ts = f"""// Generated by scripts/chart-marks.py from apps/web/public/marks. Do not edit.
// The brand's marks as absolute paths in a unit box (x and y from 0 to 1 across the mark's own box).

/** The flame, in a box 46 wide by 88 tall (keep that ratio). */
export const FLAME = {{ ratio: 46 / 88, d: '{flame}' }};
/**
 * The globe cut out of the flame, in the flame's units (multiply by the box width / 46): centre as a
 * share of the box, radius, the meridian ellipse's x radius and the stroke widths.
 */
export const GLOBE = {{ cx: {globe['cx']:.4f}, cy: {globe['cy']:.4f}, r: {globe['r']:.3f}, rx: {globe['rx']:.3f}, ring: {globe['ring']:.3f}, line: {globe['line']:.3f} }};
/** The hand-drawn strike through "Internet" (stretched to the word; 400 by 40). */
export const STRIKE = '{strike}';
/** The proofreader's caret (40 by 30). */
export const CARET = {{ ratio: 40 / 30, d: '{caret}' }};
"""
open(out, 'w').write(ts)
print('wrote', out)
